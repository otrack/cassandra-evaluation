#!/usr/bin/env python3
"""Records the round-trip times between the AWS regions of regions.csv, as
measured by https://www.cloudping.co/, in latencies.csv (next to this script).

Run it by hand to refresh the matrix; the experiments only read latencies.csv.

    python3 infra/aws/fetch_latencies.py

The page embeds its matrix (median over the last day, in milliseconds) as the
initialData of its React payload.  The table it renders is labelled "To \\
From": the outer key of the data is the destination and the inner key the
source.
"""

import csv
import json
import os
import re
import sys
import urllib.request
from datetime import date

URL = "https://www.cloudping.co/"
HERE = os.path.dirname(os.path.abspath(__file__))


def fetch_matrix():
    req = urllib.request.Request(URL, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        page = resp.read().decode("utf-8")
    # The React Server Components payload: JS string literals pushed in order
    chunks = re.findall(r'self\.__next_f\.push\(\[1,"(.*?)"\]\)', page, re.S)
    payload = "".join(json.loads('"' + c + '"') for c in chunks)
    start = payload.find('{"initialData"')
    if start < 0:
        sys.exit("fetch_latencies: no initialData in %s; the page has changed" % URL)
    obj, _ = json.JSONDecoder().raw_decode(payload[start:])
    return obj["initialData"]["metadata"], obj["initialData"]["data"]


def main():
    metadata, data = fetch_matrix()
    with open(os.path.join(HERE, "regions.csv"), newline="") as f:
        regions = [(row["region"], row["loc"]) for row in csv.DictReader(f)]

    rows = []
    for src, src_loc in regions:
        for dst, dst_loc in regions:
            if src == dst:
                continue
            rtt = data.get(dst, {}).get(src)
            if rtt is None:
                sys.exit("fetch_latencies: no measurement from %s to %s" % (src, dst))
            rows.append((src_loc, dst_loc, rtt))

    path = os.path.join(HERE, "latencies.csv")
    with open(path, "w", newline="") as f:
        f.write(
            "# Round-trip times between the AWS regions of regions.csv, in milliseconds,\n"
            "# from %s (percentile %s over %s, retrieved %s), one row per\n"
            "# direction, src being the region the probe was sent from. Generated by\n"
            "# fetch_latencies.py; do not edit by hand. The two directions of a pair are\n"
            "# averaged (see emulate_latency.load_measured_rtts). The simulation uses this\n"
            "# matrix too (infra/simulation/latencies.csv links here).\n"
            % (URL, metadata.get("percentile"), metadata.get("timeframe"), date.today().isoformat()))
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["src", "dst", "rtt_ms"])
        for src_loc, dst_loc, rtt in rows:
            w.writerow([src_loc, dst_loc, "%.2f" % rtt])
    print("Wrote %d measurements between %d regions to %s" % (len(rows), len(regions), path))


if __name__ == "__main__":
    main()
